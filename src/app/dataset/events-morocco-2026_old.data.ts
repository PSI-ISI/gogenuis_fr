// ============ HELPER FUNCTIONS ============
export function getEventsByCategory(category: string): Event[] {
  if (category === 'all') return EVENTS_DATA;
  return EVENTS_DATA.filter(e => e.category.toLowerCase() === category.toLowerCase());
}

export function getEventsByCity(city: string): Event[] {
  if (city === 'all') return EVENTS_DATA;
  return EVENTS_DATA.filter(e => e.city === city);
}

export function getFeaturedEvents(): Event[] {
  return EVENTS_DATA.filter(e => e.isFeatured);
}

export function getUpcomingEvents(limit?: number): Event[] {
  const today = new Date();
  const upcoming = EVENTS_DATA
    .filter(e => e.date >= today)
    .sort((a, b) => a.date.getTime() - b.date.getTime());
  return limit ? upcoming.slice(0, limit) : upcoming;
}

export function searchEvents(query: string): Event[] {
  const q = query.toLowerCase();
  return EVENTS_DATA.filter(e =>
    e.title.toLowerCase().includes(q) ||
    e.description.toLowerCase().includes(q) ||
    e.city.toLowerCase().includes(q) ||
    e.tags.some(tag => tag.toLowerCase().includes(q))
  );
}

export function getEventById(id: number): Event | undefined {
  return EVENTS_DATA.find(e => e.id === id);
}

export function getCategoryCount(categoryId: string): number {
  if (categoryId === 'all') return EVENTS_DATA.length;
  return EVENTS_DATA.filter(e => e.category.toLowerCase() === categoryId.toLowerCase()).length;
}
